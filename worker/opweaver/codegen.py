"""Deterministic readable PyTorch emission from validated Design Graphs."""

import ast
import keyword
import re

from torch import nn

from .ir import Graph
from .registry import OperatorRegistry, builtin_registry
from .source import SourceMapping, digest, graph_hash
from .validation import validate


def identifier(value: str) -> str:
    result = re.sub(r"\W", "_", value)
    if not result or result[0].isdigit() or keyword.iskeyword(result):
        result = "node_" + result
    return result


def generate(
    graph: Graph,
    registry: OperatorRegistry | None = None,
    file_path="src/model.py",
    class_name="OpWeaverModel",
) -> dict:
    registry = registry or builtin_registry()
    report = validate(graph, registry)
    if not report.valid:
        raise ValueError(
            "Cannot generate code from an invalid graph: "
            + "; ".join(i["message"] for i in report.issues)
        )
    if not class_name.isidentifier() or keyword.iskeyword(class_name):
        raise ValueError("Class name must be a Python identifier")
    nodes = {node.id: node for node in graph.nodes}
    names, used = {}, set(dir(nn.Module)) | {"training"}
    for node in graph.nodes:
        name = identifier(node.id)
        while name in used:
            name += "_"
        used.add(name)
        names[node.id] = name
    imports = {
        line
        for node in graph.nodes
        for line in registry.get(node.operator.id, node.operator.version).python_imports
    }
    lines = [
        "# Generated by OpWeaver Studio. Edit freely; changes are never silently overwritten.",
        "import torch",
        "from torch import nn",
        *sorted(imports),
        "",
        "",
        f"class {class_name}(nn.Module):",
        "    def __init__(self):",
        "        super().__init__()",
    ]
    mappings = []
    node_ids = {}
    for node in graph.nodes:
        op = registry.get(node.operator.id, node.operator.version)
        if node.share_with or node.operator.id in ("core.input", "core.output"):
            continue
        if op.python_module:
            lines.append(
                f"        self.{names[node.id]} = {op.python_module(op.parameters.model_validate(node.params))}"
            )
            node_ids[names[node.id]] = node.id
            mappings.append(
                SourceMapping(
                    file_path=file_path,
                    start_line=len(lines),
                    end_line=len(lines),
                    module_path=names[node.id],
                    graph_node_id=node.id,
                    status="exact",
                )
            )
        elif not op.python_expression:
            raise ValueError(f"Operator {op.id}@{op.version} has no code generation capability")
    # Kept as inert literal metadata so capture can recover design IDs, not FX names.
    lines.extend(["", f"    _opweaver_node_ids = {node_ids!r}"])
    input_nodes = [node for node in graph.nodes if node.operator.id == "core.input"]
    arguments = [f"input_{index}" for index in range(len(input_nodes))]
    input_ids = {name: node.id for node, name in zip(input_nodes, arguments)}
    lines.append(f"    _opweaver_input_ids = {input_ids!r}")
    lines.extend(["", "    def forward(self, " + ", ".join(arguments) + "):"])
    incoming = {(e.target, e.target_port): (e.source, e.source_port) for e in graph.edges}
    values = {(node.id, "out"): name for node, name in zip(input_nodes, arguments)}
    expressions = {}
    for id in report.order:
        node = nodes[id]
        if node.operator.id in ("core.input", "core.output"):
            continue
        if len(node.outputs) != 1:
            raise ValueError(
                f"Code generation for multi-output operator {id} requires a dedicated emitter"
            )
        op = registry.get(node.operator.id, node.operator.version)
        args = [values[incoming[id, port.name]] for port in node.inputs]
        owner = node.share_with or id
        expression = (
            f"self.{names[owner]}({', '.join(args)})"
            if op.python_module
            else op.python_expression(args, op.parameters.model_validate(node.params))
        )
        name = "tensor_" + names[id]
        lines.append(f"        {name} = {expression}")
        expressions[name] = id
        values[id, node.outputs[0].name] = name
        if not any(m.graph_node_id == id for m in mappings):
            mappings.append(
                SourceMapping(
                    file_path=file_path,
                    start_line=len(lines),
                    end_line=len(lines),
                    graph_node_id=id,
                    module_path=names[owner] if op.python_module else "",
                    status="exact",
                )
            )
    output_nodes = [node for node in graph.nodes if node.operator.id == "core.output"]
    results = [values[incoming[node.id, "in"]] for node in output_nodes]
    lines.append(
        "        return " + (results[0] if len(results) == 1 else "(" + ", ".join(results) + ")")
    )
    lines.append("")
    for node in input_nodes + output_nodes:
        mappings.append(
            SourceMapping(
                file_path=file_path,
                start_line=len(lines) - 1
                if node in output_nodes
                else lines.index("    def forward(self, " + ", ".join(arguments) + "):") + 1,
                end_line=None,
                graph_node_id=node.id,
                status="exact",
            )
        )
    # Result/input/functional metadata can be read statically and is ignored by PyTorch.
    lines.extend(
        [
            f"    _opweaver_expression_ids = {expressions!r}",
            f"    _opweaver_output_ids = {[n.id for n in output_nodes]!r}",
            "",
        ]
    )
    text = "\n".join(lines)
    ast.parse(text)
    return {
        "text": text,
        "class_name": class_name,
        "source_hash": digest(text),
        "graph_hash": graph_hash(graph),
        "source_map": [m.model_dump() for m in mappings],
        "graph": graph.model_dump(),
    }
