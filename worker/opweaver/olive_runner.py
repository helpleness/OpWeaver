from opweaver.model_files import atomic_replace  # noqa: E402

PASS_MODULES = {
    "OnnxPeepholeOptimizer": (
        "olive.passes.onnx.peephole_optimizer",
        ["onnxscript_optimize", "onnxoptimizer_optimize", "fuse_reshape_operations"],
    ),
    "OnnxOpVersionConversion": ("olive.passes.onnx.conversion", ["target_opset"]),
    "OnnxQuantizationPreprocess": (
        "olive.passes.onnx.quantization",
        ["skip_optimization", "skip_onnx_shape", "skip_symbolic_shape"],
    ),
    "OnnxStaticQuantization": (
        "olive.passes.onnx.quantization",
        [
            "precision",
            "activation_type",
            "quant_format",
            "calibrate_method",
            "per_channel",
            "activation_symmetric",
            "weight_symmetric",
            "op_types_to_quantize",
            "op_types_to_exclude",
            "nodes_to_exclude",
        ],
    ),
}


def write(path, value):
    temporary = path.with_suffix(".tmp")
    temporary.write_text(
        json.dumps(value, ensure_ascii=True, allow_nan=False, indent=2), encoding="utf-8"
    )
    atomic_replace(temporary, path)


def environment_probe():
    versions = {"python": platform.python_version()}
    for distribution in [
        "olive-ai",
        "onnx",
        "onnxruntime",
        "onnxscript",
        "onnx-ir",
        "onnxoptimizer",
        "torch",
        "pydantic",
        "numpy",
    ]:
        try:
            versions[distribution] = importlib.metadata.version(distribution)
        except importlib.metadata.PackageNotFoundError:
            versions[distribution] = None
    result = {
        "status": "Not Installed",
        "available": False,
        "versions": versions,
        "python_path": sys.executable,
        "prefix": sys.prefix,
        "base_prefix": sys.base_prefix,
        "isolated_venv": sys.prefix != sys.base_prefix,
        "installation": None,
        "passes": [],
        "errors": [],
        "telemetry_disabled": os.environ["OLIVE_DISABLE_TELEMETRY"] == "1",
    }
    if not versions["olive-ai"]:
        return {**result, "reason": "olive-ai is not installed in this interpreter"}
    if versions["olive-ai"].split(".")[:2] != ["0", "13"]:
        return {
            **result,
            "status": "Version Incompatible",
            "reason": f"Olive {versions['olive-ai']} is outside the verified 0.13.x API compatibility rule",
        }
    required = ["onnx", "onnxruntime", "onnxscript", "onnx_ir", "torch", "pydantic", "numpy"]
    for name in required:
        try:
            importlib.import_module(name)
        except Exception as exc:
            result["errors"].append(
                {
                    "code": "MISSING_DEPENDENCY",
                    "dependency": name,
                    "message": f"{type(exc).__name__}: {exc}",
                }
            )
    if result["errors"]:
        return {
            **result,
            "status": "Missing Dependency",
            "reason": "One or more required Olive dependencies failed to import",
        }
    try:
        import olive
        import onnx
        import onnxruntime as ort
        from olive.hardware.accelerator import AcceleratorSpec, Device
        from olive.workflows.run.run import run  # noqa: F401

        result["installation"] = str(Path(olive.__file__).parent)
        result["providers"] = ort.get_available_providers()
        if "CPUExecutionProvider" not in result["providers"]:
            return {
                **result,
                "status": "Missing Dependency",
                "reason": "CPUExecutionProvider is unavailable",
            }
        accelerator = AcceleratorSpec(Device.CPU, "CPUExecutionProvider")
        for name, (module, keys) in PASS_MODULES.items():
            try:
                cls = getattr(importlib.import_module(module), name)
                native = cls._default_config(accelerator)
                if any(key not in native for key in keys):
                    raise ValueError("Installed pass parameters differ from the verified contract")
                parameters = []
                for key in keys:
                    value = native[key]
                    enums = {
                        "precision": ["int8", "uint8"],
                        "activation_type": ["int8", "uint8"],
                        "quant_format": ["QDQ", "QOperator"],
                        "calibrate_method": ["MinMax", "Entropy", "Percentile"],
                    }
                    defaults = {
                        "precision": "int8",
                        "activation_type": "int8",
                        "quant_format": "QDQ",
                        "calibrate_method": "MinMax",
                        "weight_symmetric": True,
                        "op_types_to_quantize": ["Conv", "MatMul", "Gemm"],
                        "op_types_to_exclude": [],
                        "nodes_to_exclude": [],
                    }
                    parameters.append(
                        {
                            "name": key,
                            "type": "enum"
                            if key in enums
                            else "strings"
                            if key
                            in ("op_types_to_quantize", "op_types_to_exclude", "nodes_to_exclude")
                            else "boolean"
                            if value.type_ is bool
                            else "integer",
                            "default": defaults.get(key, value.default_value),
                            **({"choices": enums[key]} if key in enums else {}),
                            "description": value.description or "",
                            **(
                                {"minimum": 13, "maximum": onnx.defs.onnx_opset_version()}
                                if key == "target_opset"
                                else {}
                            ),
                        }
                    )
                if name == "OnnxStaticQuantization":
                    from onnxruntime.quantization import CalibrationMethod, QuantFormat, QuantType
                    from onnxruntime.quantization.registry import QDQRegistry, QLinearOpsRegistry

                    for key in ("MinMax", "Entropy", "Percentile"):
                        getattr(CalibrationMethod, key)
                    for key in ("QDQ", "QOperator"):
                        getattr(QuantFormat, key)
                    for key in ("QInt8", "QUInt8"):
                        getattr(QuantType, key)
                    operators = sorted(set(QDQRegistry) | set(QLinearOpsRegistry))
                    for p in parameters:
                        if p["name"] in ("op_types_to_quantize", "op_types_to_exclude"):
                            p["choices"] = operators
                if name == "OnnxPeepholeOptimizer":
                    try:
                        importlib.import_module("onnxoptimizer")
                    except Exception as exc:
                        next(p for p in parameters if p["name"] == "onnxoptimizer_optimize").update(
                            default=False,
                            available=False,
                            reason=f"Optional onnxoptimizer failed to import: {type(exc).__name__}: {exc}",
                        )
                result["passes"].append(
                    {
                        "type": name,
                        "available": True,
                        "parameters": parameters,
                        "formats": ["onnx"],
                        "model_constraint": "Local standard ONNX graph; concrete runtime compatibility is checked by the existing CPU validation/benchmark engine",
                    }
                )
            except Exception as exc:
                result["passes"].append(
                    {
                        "type": name,
                        "available": False,
                        "parameters": [],
                        "reason": f"{type(exc).__name__}: {exc}",
                    }
                )
        return {
            **result,
            "status": "Available"
            if any(p["available"] for p in result["passes"])
            else "Missing Dependency",
            "available": any(p["available"] for p in result["passes"]),
            "reason": "Verified Olive 0.13.x local CPU workflow API",
        }
    except ModuleNotFoundError as exc:
        return {
            **result,
            "status": "Missing Dependency",
            "reason": str(exc),
            "errors": [{"code": "MISSING_DEPENDENCY", "dependency": exc.name, "message": str(exc)}],
        }
    except Exception as exc:
        return {
            **result,
            "status": "Environment Error",
            "reason": f"{type(exc).__name__}: {exc}",
            "errors": [{"code": "OLIVE_IMPORT_FAILED", "message": str(exc)}],
        }


def normalized_graph(path):
    import hashlib

    import onnx

    model = onnx.load(str(path), load_external_data=True)
    return {
        "sha256": hashlib.sha256(model.graph.SerializeToString(deterministic=True)).hexdigest(),
        "nodes": len(model.graph.node),
    }


def validate_native(native):
    from olive.workflows.run.config import RunConfig

    return RunConfig.parse_file_or_obj(copy.deepcopy(native))


def run_workflow(request, result_path):
    from olive.model import ModelConfig
    from olive.workflows.run.run import run

    native = request["native"]
    validated = validate_native(native)
    write(result_path.parent / "executed-workflow.json", validated.to_json())
    started = time.time()
    output = run(copy.deepcopy(native), tempdir=str(result_path.parent / "tmp"))
    if output is None or not output.has_output_model():
        raise ValueError("Olive returned no output candidates; inspect the raw workflow logs")
    executed = [
        {
            "model_id": node.model_id,
            "parent_model_id": node.parent_model_id,
            "pass_type": node.from_pass,
            "config": node.pass_run_config,
            "start_time": node.start_time,
            "end_time": node.end_time,
            "produced_model": bool(node.model_config_data),
            "model_config": node.model_config_data,
        }
        for node in output.footprint.nodes.values()
        if node.from_pass
    ]
    for item in executed:
        if item["produced_model"] and item["pass_type"].lower() == "onnxquantizationpreprocess":
            item["artifact_path"] = str(
                ModelConfig.parse_file_or_obj(item["model_config"]).create_model().model_path
            )
    write(result_path.parent / "pass-results.json", {"executed_passes": executed})
    expected = [p["type"].lower() for p in native["passes"].values()]
    if [p["pass_type"].lower() for p in executed if p["produced_model"]] != expected:
        raise ValueError(
            "Olive did not complete every enabled pass in the requested order; inspect the footprint and raw logs"
        )
    candidates = []
    root = result_path.parent.resolve()
    source_signature = normalized_graph(request["source"])
    for item in output.get_output_models():
        model = ModelConfig.parse_file_or_obj(item.olive_model_config).create_model()
        path = Path(model.model_path).resolve(strict=True)
        if item.model_type.lower() != "onnxmodel" or not path.is_relative_to(root):
            raise ValueError("Olive returned a non-local/non-ONNX artifact outside the experiment")
        olive_path = str(path)
        published = path.with_name(request["output_model_name"])
        if published != path:
            shutil.copy2(path, published)
            path = published
        signature = normalized_graph(path)
        candidates.append(
            {
                "id": item.model_id,
                "model_path": str(path),
                "olive_model_path": olive_path,
                "model_type": item.model_type,
                "inference_config": item.get_inference_config(),
                "parent_model_id": item.get_parent_model_id(),
                "from_pass": item.from_pass(),
                "graph_signature": signature,
                "observed_graph_change": signature["sha256"] != source_signature["sha256"],
            }
        )
    return {
        "success": True,
        "started_at": started,
        "finished_at": time.time(),
        "native_workflow": native,
        "executed_workflow": validated.to_json(),
        "requested_passes": request["requested_passes"],
        "executed_passes": executed,
        "candidates": candidates,
        "selected_candidate_id": candidates[0]["id"],
        "source_graph_signature": source_signature,
        "transformation_note": "Graph digest/node changes are observed on loaded ONNX graphs; exact optimizer rewrite rules are not inferred. Executed passes may produce no structural change.",
        "telemetry_disabled": True,
    }


def main():
    mode, request_name, result_name = sys.argv[1:4]
    request_path, result_path = Path(request_name), Path(result_name)
    request = json.loads(request_path.read_text(encoding="utf-8"))
    if mode == "run":
        write(
            result_path.parent / "process.json",
            {"pid": os.getpid(), "owner_pid": request.get("owner_pid"), "started_at": time.time()},
        )
    if request.get("owner_pid"):
        from opweaver.process_owner import watch_owner

        watch_owner(
            request["owner_pid"],
            Path(request["cancellation"]) if request.get("cancellation") else None,
        )
    try:
        if mode == "probe":
            result = environment_probe()
        elif mode == "validate":
            result = {
                "success": True,
                "executed_config": validate_native(request["native"]).to_json(),
            }
        elif mode == "run":
            result = run_workflow(request, result_path)
        else:
            raise ValueError("Unsupported Olive bridge operation")
    except Exception as exc:
        traceback.print_exc()
        result = {"success": False, "error": f"{type(exc).__name__}: {exc}"}
    write(result_path, result)


if __name__ == "__main__":
    main()
